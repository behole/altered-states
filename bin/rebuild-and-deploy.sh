#!/usr/bin/env bash
#
# Rebuild the site and publish it when the content changed.
# Cron target — picks up new journal entries and deploys to Cloudflare Pages.
#
# `main` is protected: CI must pass and changes arrive through a pull request.
# This script therefore pushes to a short-lived branch and lets GitHub auto-merge
# the pull request once the checks are green. If auto-merge cannot be enabled
# (for example the checks have not registered yet), the script leaves the pull
# request open and says so, rather than pushing straight to `main`.

set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
LOG="${SITE_REBUILD_LOG:-/tmp/site-rebuild.log}"
BRANCH="chore/site-autorebuild"
BASE_BRANCH="${SITE_REBUILD_BASE:-main}"

cd "$REPO_ROOT"

log() { printf '%s\n' "$*" | tee -a "$LOG"; }

log "=== $(date) ==="

# 1. Rebuild the site.
python3 build.py >> "$LOG" 2>&1

# 2. Stop if nothing changed.
if git diff --quiet -- site/ && git diff --cached --quiet -- site/; then
    log "No site changes to push"
    exit 0
fi

# 3. Publish through a pull request so the protected branch's checks run.
git checkout -B "$BRANCH" >/dev/null 2>&1
git add site/
git commit -m "chore(site): auto-rebuild $(date '+%Y-%m-%d %H:%M')" >> "$LOG" 2>&1
git push --force-with-lease origin "$BRANCH" >> "$LOG" 2>&1

if ! command -v gh >/dev/null 2>&1; then
    log "Pushed $BRANCH but the GitHub CLI is missing; open the pull request by hand."
    exit 1
fi

# Reuse the open pull request for this branch if there is one.
PR_NUMBER="$(gh pr list --head "$BRANCH" --state open --json number --jq '.[0].number // empty')"
if [ -z "$PR_NUMBER" ]; then
    PR_NUMBER="$(gh pr create \
        --head "$BRANCH" \
        --base "$BASE_BRANCH" \
        --title "chore(site): auto-rebuild $(date '+%Y-%m-%d')" \
        --body "Automated site rebuild. Generated by \`bin/rebuild-and-deploy.sh\`." \
        --json number --jq '.number')"
    log "Opened pull request #$PR_NUMBER"
fi

# Auto-merge respects the required checks: it merges when CI is green and does
# nothing when CI is red.
if gh pr merge "$PR_NUMBER" --squash --auto >> "$LOG" 2>&1; then
    log "Auto-merge armed for pull request #$PR_NUMBER"
else
    log "Could not arm auto-merge on #$PR_NUMBER; it is open and waiting for a human."
    exit 1
fi

git checkout "$BASE_BRANCH" >/dev/null 2>&1
git pull --ff-only origin "$BASE_BRANCH" >> "$LOG" 2>&1 || log "Could not fast-forward $BASE_BRANCH; that is fine, the merge will."

log "Done"
